#!/usr/bin/env python3
"""Reuse the parallel preparation's recent public model identity evidence, transparently."""
from common import *
import time

def main():
 shared=Path('/home/gpu/IntentSat2S_revision_20261106/new_glm_context')
 original=shared/'prepared/MODEL_FILE_SHA256.json'
 model_data=json.loads(original.read_text())
 evidence_files=[shared/'provenance/MODEL_SNAPSHOT_VERIFICATION.json',shared/'provenance/MODEL_LOCAL_RECHECK_QWEN_SMOL.json']
 evidence={p.name:json.loads(p.read_text()) for p in evidence_files}
 assert evidence['MODEL_SNAPSHOT_VERIFICATION.json']['status']=='PASS'
 assert all(x['status']=='PASS' for x in evidence['MODEL_LOCAL_RECHECK_QWEN_SMOL.json']['models'].values())
 cleaned={};local_stats={}
 for model in MODELS:
  entry=model_data[model];path=Path(entry['path'])
  assert str(path)==json.loads((ROOT/'model_locations.json').read_text())[model]
  # Exclude local downloader bookkeeping; never read its contents.
  files={name:value for name,value in entry['files'].items() if not name.startswith('.')}
  cleaned[model]={**{k:v for k,v in entry.items() if k!='files'},'files':files}
  local_stats[model]={}
  for name,want in files.items():
   p=path/name;s=p.stat();local_stats[model][name]={'bytes':s.st_size,'mtime_ns':s.st_mtime_ns}
   snap=ROOT/'tokenizers'/model/name
   if snap.is_file():assert sha(snap)==want
  cleaned[model]['provenance_basis']='Reused recent shared current-model verification, not rehashed in SNLI CPU phase; full check still required by inference runner before any judgment'
 write_json(ROOT/'prepared/MODEL_FILE_SHA256.json',cleaned)
 write_json(ROOT/'prepared/MODEL_IDENTITY_PROVENANCE.json',{'created_unix':time.time(),
  'method':'Read-only reuse of current verification evidence generated by the parallel GLM-context preparation; tokenizer/config copies checked against those hashes here',
  'shared_manifest':{'path':str(original),'sha256':sha(original)},
  'shared_evidence':{str(p):{'sha256':sha(p),'status':'PASS','created_unix':evidence[p.name]['created_unix']} for p in evidence_files},
  'local_public_asset_stats':local_stats,'weights_rehashed_by_this_SNLI_task':False,
  'inference_gate':'Runner must recheck these fixed model hashes before new judgments; independent review and GPU GO still pending',
  'local_download_bookkeeping':'Excluded; contents not read'})
 print('Fixed public model identity imported with explicit shared-evidence provenance; no weights loaded or rehashed',flush=True)

if __name__=='__main__':main()
